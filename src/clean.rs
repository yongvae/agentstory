//! Turning raw transcript text into what a person actually said, and scrubbing secrets.

use regex::Regex;
use std::sync::LazyLock;

use crate::config::{CONFIG, Transcript};

/// Wrappers agents themselves put around context (not a person's words).
const BUILTIN_DROP_TAGS: &[&str] = &[
    "system-reminder",
    "environment_context",
    "user_instructions",
    "ide_opened_file",
    "ide_selection",
    "command-message",
    "local-command-stdout",
    "timestamp",
];
/// Agents' own wrappers around what the person typed (Cursor: <user_query>).
const BUILTIN_MESSAGE_TAGS: &[&str] = &["user_query"];

/// Compiled transcript-cleaning rules: built-ins plus the user's config.
pub struct Rules {
    drop: Regex,
    message: Vec<Regex>,
    speaker: Option<Regex>,
    self_closing: Option<Regex>,
    speaker_patterns: Vec<Regex>,
    strip: Vec<Regex>,
    relay: Vec<(Regex, Regex, String)>,
    silent: Vec<String>,
}

fn tag_pattern(tag: &str) -> String {
    match tag.strip_suffix('*') {
        Some(prefix) => format!(
            r"(?s)<{p}[A-Za-z0-9_-]*\b[^>]*>.*?</{p}[A-Za-z0-9_-]*>",
            p = regex::escape(prefix)
        ),
        None => format!(r"(?s)<{t}\b[^>]*>.*?</{t}>", t = regex::escape(tag)),
    }
}

fn compile_all(pats: &[String]) -> Vec<Regex> {
    pats.iter()
        .filter_map(|p| match Regex::new(p) {
            Ok(r) => Some(r),
            Err(e) => {
                eprintln!("agentstory: ignoring config pattern {p:?}: {e}");
                None
            }
        })
        .collect()
}

impl Rules {
    pub fn new(t: &Transcript) -> Rules {
        let tags: Vec<String> = BUILTIN_DROP_TAGS
            .iter()
            .map(|s| s.to_string())
            .chain(t.drop_tags.iter().cloned())
            .collect();
        let drop = Regex::new(
            &tags
                .iter()
                .map(|t| format!("(?:{})", tag_pattern(t)))
                .collect::<Vec<_>>()
                .join("|"),
        )
        .unwrap();
        let message = BUILTIN_MESSAGE_TAGS
            .iter()
            .map(|s| s.to_string())
            .chain(t.message_tags.iter().cloned())
            .map(|tag| {
                Regex::new(&format!(r"(?s)<{t}>(.*?)</{t}>", t = regex::escape(&tag))).unwrap()
            })
            .collect();
        let (speaker, self_closing) = match &t.speaker_tag {
            Some(tag) => {
                let attr = t.speaker_attr.clone().unwrap_or_else(|| "name".into());
                (
                    Regex::new(&format!(
                        r#"<{}\b[^>]*?\s{}="([^"]+)""#,
                        regex::escape(tag),
                        regex::escape(&attr)
                    ))
                    .ok(),
                    Regex::new(&format!(r"<{}\b[^>]*/>", regex::escape(tag))).ok(),
                )
            }
            None => (None, None),
        };
        let relay = t
            .relay_commands
            .iter()
            .map(|c| {
                let c = regex::escape(c.trim()).replace(r"\ ", r"\s+");
                (
                    Regex::new(&format!(r"(?s){c}[^\n]*?<<-?'?EOF'?\n(.*?)\nEOF")).unwrap(),
                    Regex::new(&format!(
                        r#"{c}(?:\s+--[\w-]+(?:\s+[^\s"-][^\s"]*)?)*\s+"((?:[^"\\]|\\.)*)""#
                    ))
                    .unwrap(),
                    c,
                )
            })
            .collect();
        Rules {
            drop,
            message,
            speaker,
            self_closing,
            speaker_patterns: compile_all(&t.speaker_patterns),
            strip: compile_all(&t.strip_patterns),
            relay,
            silent: t.silent_replies.clone(),
        }
    }
}

static RULES: LazyLock<Rules> = LazyLock::new(|| Rules::new(&CONFIG.transcript));
static WS: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"\s+").unwrap());

pub struct Cleaned {
    pub text: String,
    pub author: Option<String>,
    /// Harness-generated input rather than a person.
    pub is_system: bool,
    pub is_summary: bool,
}

const SUMMARY_MARKERS: &[&str] = &[
    "This session is being continued from a previous conversation",
    "<summary>",
];
const SYSTEM_MARKERS: &[&str] = &[
    "[SYSTEM NOTIFICATION",
    "<task-notification>",
    "Stop hook feedback",
    "<command-name>",
    "Caveat: The messages below were generated by the user while running local commands",
    "[Request interrupted by user",
];

/// Clean one user-side message. Returns None if nothing human is left.
pub fn user_text(raw: &str) -> Option<Cleaned> {
    user_text_with(raw, &RULES)
}

pub fn user_text_with(raw: &str, r: &Rules) -> Option<Cleaned> {
    let is_summary = SUMMARY_MARKERS.iter().any(|m| raw.contains(m));
    let author = r
        .speaker
        .as_ref()
        .and_then(|re| re.captures(raw))
        .map(|c| c[1].to_string())
        .or_else(|| {
            r.speaker_patterns
                .iter()
                .find_map(|re| re.captures(raw).map(|c| c[1].to_string()))
        });
    let inner = r
        .message
        .iter()
        .find_map(|re| re.captures(raw).map(|c| c[1].to_string()))
        .unwrap_or_else(|| raw.to_string());
    let mut text = r.drop.replace_all(&inner, "").into_owned();
    if let Some(sc) = &r.self_closing {
        text = sc.replace_all(&text, "").into_owned();
    }
    for re in &r.strip {
        text = re.replace_all(&text, "").into_owned();
    }
    let text = text.trim().to_string();
    if text.is_empty() {
        return None;
    }
    let is_system = !is_summary && SYSTEM_MARKERS.iter().any(|m| raw.contains(m));
    Some(Cleaned {
        text,
        author,
        is_system,
        is_summary,
    })
}

/// Assistant text that means "nothing to say" (configured per harness).
pub fn is_silent(text: &str) -> bool {
    let t = text.trim();
    t.is_empty() || RULES.silent.iter().any(|s| s == t)
}

pub fn one_line(s: &str, max_chars: usize) -> String {
    let t = WS.replace_all(s.trim(), " ");
    truncate(&t, max_chars)
}

/// First `head` and last `tail` chars: outputs tend to end with the error.
pub fn head_tail(s: &str, head: usize, tail: usize) -> String {
    let n = s.chars().count();
    if n <= head + tail {
        return s.to_string();
    }
    let start: String = s.chars().take(head).collect();
    let end: String = s.chars().skip(n - tail).collect();
    format!("{start}\n…\n{end}")
}

/// What connectors keep of one tool output: the start and the end (where errors are).
pub fn tool_output(s: &str) -> String {
    head_tail(s, 1500, 500)
}

pub fn truncate(s: &str, max_chars: usize) -> String {
    if s.chars().count() <= max_chars {
        s.to_string()
    } else {
        let mut out: String = s.chars().take(max_chars).collect();
        out.push('…');
        out
    }
}

struct Rule(Regex, &'static str);

static REDACTIONS: LazyLock<Vec<Rule>> = LazyLock::new(|| {
    let r = |p: &str, rep: &'static str| Rule(Regex::new(p).unwrap(), rep);
    vec![
        r(
            r"(?s)-----BEGIN [A-Z ]*PRIVATE KEY-----.*?-----END [A-Z ]*PRIVATE KEY-----",
            "[REDACTED:private-key]",
        ),
        r(r"\b(?:sk|pk|rk)-[A-Za-z0-9_\-]{16,}", "[REDACTED:key]"),
        r(
            r"\b(?:ghp|gho|ghs|ghu|github_pat|glpat|xox[abpr])[_\-][A-Za-z0-9_]{16,}",
            "[REDACTED:token]",
        ),
        r(r"\bAKIA[0-9A-Z]{16}\b", "[REDACTED:aws-key]"),
        r(r"\bAIza[0-9A-Za-z_\-]{30,}", "[REDACTED:google-key]"),
        r(
            r"\beyJ[A-Za-z0-9_\-]{10,}\.[A-Za-z0-9_\-]{10,}\.[A-Za-z0-9_\-]{5,}",
            "[REDACTED:jwt]",
        ),
        r(r"(?i)\b(bearer)\s+[A-Za-z0-9._\-]{16,}", "$1 [REDACTED]"),
        r(
            r#"(?i)((?:api[_-]?key|access[_-]?token|auth[_-]?token|token|secret|password|passwd|pwd|cookie|authorization)\s*["']?\s*[:=]\s*["']?)[^\s"',;}]{6,}"#,
            "${1}[REDACTED]",
        ),
        r(r"\b[A-Fa-f0-9]{48,}\b", "[REDACTED:hex]"),
        r(r"\b\d{17}[\dXx]\b", "[REDACTED:id-number]"),
        r(r"\b1[3-9]\d{9}\b", "[REDACTED:phone]"),
    ]
});

/// Long opaque strings: only redacted when they look random (mixed case and digits), so
/// slugs like `2026-10-01-ask-auth-model-before-picking-docs` and paths survive.
static BLOB: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"\b[A-Za-z0-9+_\-]{32,}={0,2}").unwrap());

fn looks_random(s: &str) -> bool {
    let upper = s.chars().filter(|c| c.is_ascii_uppercase()).count();
    let lower = s.chars().filter(|c| c.is_ascii_lowercase()).count();
    let digit = s.chars().filter(|c| c.is_ascii_digit()).count();
    let seps = s.chars().filter(|c| matches!(c, '-' | '/' | '_')).count();
    upper >= 3 && lower >= 3 && digit >= 2 && seps * 8 < s.len()
}

/// Remove credentials and personal identifiers before anything is stored or printed.
pub fn redact(s: &str) -> String {
    redact_labeled(s).0
}

/// Like [`redact`], also returning which kinds of secret were found.
pub fn redact_labeled(s: &str) -> (String, Vec<&'static str>) {
    let mut out = s.to_string();
    let mut found = vec![];
    for Rule(re, rep) in REDACTIONS.iter() {
        if re.is_match(&out) {
            found.push(*rep);
            out = re.replace_all(&out, *rep).into_owned();
        }
    }
    if BLOB.is_match(&out) {
        let mut hit = false;
        let replaced = BLOB
            .replace_all(&out, |c: &regex::Captures| {
                if looks_random(&c[0]) {
                    hit = true;
                    "[REDACTED:blob]".to_string()
                } else {
                    c[0].to_string()
                }
            })
            .into_owned();
        if hit {
            found.push("[REDACTED:blob]");
        }
        out = replaced;
    }
    (out, found)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A fictional chat bridge, configured the way a user would.
    fn bridge() -> Rules {
        Rules::new(&Transcript {
            drop_tags: vec!["router_*".into()],
            message_tags: vec!["chat_message".into()],
            speaker_tag: Some("from".into()),
            speaker_attr: None,
            speaker_patterns: vec![r"\[relayed by (\S+)\]".into()],
            strip_patterns: vec![
                r"\[bridge note[^\]]*\]\s*".into(),
                r"\[relayed by \S+\]\s*".into(),
            ],
            relay_commands: vec!["chatctl send".into()],
            silent_replies: vec!["NO_REPLY".into()],
        })
    }

    #[test]
    fn unwraps_configured_chat_envelope_and_finds_speaker() {
        let r = bridge();
        let raw = "<router_rules>x</router_rules>\n<chat_message>\n@bot 帮我查一下\n</chat_message>\n<from id=\"1\" name=\"张三\" />";
        let c = user_text_with(raw, &r).unwrap();
        assert_eq!(c.text, "@bot 帮我查一下");
        assert_eq!(c.author.as_deref(), Some("张三"));
        let q = user_text_with(
            "<chat_message>[bridge note: quoted 1]\n@bot 看看</chat_message>",
            &r,
        )
        .unwrap();
        assert_eq!(q.text, "@bot 看看");
        let relayed = user_text_with("[relayed by HelperBot] please continue", &r).unwrap();
        assert_eq!(relayed.author.as_deref(), Some("HelperBot"));
        assert_eq!(relayed.text, "please continue");
    }

    #[test]
    fn without_config_text_is_kept_as_is() {
        let raw = "<chat_message>hi</chat_message>";
        assert_eq!(
            user_text_with(raw, &Rules::new(&Transcript::default()))
                .unwrap()
                .text,
            raw
        );
        let cursor = "<timestamp>Monday</timestamp>\n<user_query>\nfix it\n</user_query>";
        assert_eq!(
            user_text_with(cursor, &Rules::new(&Transcript::default()))
                .unwrap()
                .text,
            "fix it"
        );
    }

    #[test]
    fn flags_notifications_and_summaries() {
        assert!(
            user_text("[SYSTEM NOTIFICATION - NOT USER INPUT] done")
                .unwrap()
                .is_system
        );
        let s = user_text(
            "This session is being continued from a previous conversation that ran out of context.",
        )
        .unwrap();
        assert!(s.is_summary && !s.is_system);
        assert!(user_text("<system-reminder>only noise</system-reminder>").is_none());
    }

    #[test]
    fn redacts_common_secrets() {
        let s = redact(
            "key sk-abcdefghijklmnopqrstuv and token=abcdef123456 and 13812345678 and ghp_abcdefghijklmnopqrstuvwxyz",
        );
        assert!(!s.contains("sk-abcdef"));
        assert!(!s.contains("abcdef123456"));
        assert!(!s.contains("13812345678"));
        assert!(!s.contains("ghp_abc"));
        assert!(s.contains("token=[REDACTED]"));
    }

    #[test]
    fn keeps_slugs_but_not_random_blobs() {
        let slug = "see mistakes/2026-10-01-ask-auth-model-before-picking-docs.md";
        assert_eq!(redact(slug), slug);
        assert!(redact("x 9fQ2kLmZ81xPqRtY7vBnW3eCsD4gHjK0aUiOpLz y").contains("[REDACTED:blob]"));
    }

    #[test]
    fn keeps_ordinary_text() {
        let t = "把 bin/recall 改成 Rust，路径 /Users/x/dev/app/CLAUDE.md";
        assert_eq!(redact(t), t);
    }
}

/// Messages an agent sent to a chat through a relay command (configured in `relay_commands`)
/// are part of what it "said", even though they live inside a shell command.
pub fn relayed_reply(command: &str) -> Option<String> {
    relayed_reply_with(command, &RULES)
}

pub fn relayed_reply_with(command: &str, r: &Rules) -> Option<String> {
    for (heredoc, quoted, _) in &r.relay {
        let mut parts: Vec<String> = heredoc
            .captures_iter(command)
            .map(|c| c[1].to_string())
            .collect();
        if parts.is_empty() {
            parts = quoted
                .captures_iter(command)
                .map(|c| c[1].replace("\\n", "\n").replace("\\\"", "\""))
                .collect();
        }
        if !parts.is_empty() {
            return Some(parts.join("\n"));
        }
    }
    None
}

#[cfg(test)]
mod relay_tests {
    use super::*;
    #[test]
    fn extracts_relay_text() {
        let r = Rules::new(&crate::config::Transcript {
            relay_commands: vec!["chatctl send".into()],
            ..Default::default()
        });
        let c = "chatctl send --quiet <<'EOF'\n第一行\n第二行\nEOF\necho hi";
        assert_eq!(relayed_reply_with(c, &r).unwrap(), "第一行\n第二行");
        assert_eq!(
            relayed_reply_with("chatctl send --quiet \"好的\"", &r).unwrap(),
            "好的"
        );
        assert!(relayed_reply_with("ls", &r).is_none());
        assert!(
            relayed_reply_with(c, &Rules::new(&Default::default())).is_none(),
            "nothing without config"
        );
    }
}
