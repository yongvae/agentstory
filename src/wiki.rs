//! Export sessions as a Markdown wiki: one page per session, one digest per day, an index.
//! The output is plain files, so any knowledge base (Obsidian, a git repo, a docs site, an
//! agent's memory folder) can use it.

use crate::clean::one_line;
use crate::handoff;
use crate::index::{Filter, Index};
use crate::model::turns;
use crate::render::{self, View};
use crate::time::{day_local, fmt_local};
use anyhow::Result;
use serde::Serialize;
use std::collections::BTreeMap;
use std::path::Path;

#[derive(Debug, Default, Serialize)]
pub struct WikiStats {
    pub sessions: usize,
    pub pages_written: usize,
    pub pages_unchanged: usize,
    pub days: usize,
}

pub fn page_name(agent: &str, id: &str, started: Option<i64>) -> String {
    let safe: String = id
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '-' || *c == '_')
        .take(36)
        .collect();
    format!("{}-{}-{}", day_local(started), agent, safe)
}

fn write_if_changed(path: &Path, body: &str, st: &mut WikiStats) -> Result<()> {
    if std::fs::read_to_string(path).ok().as_deref() == Some(body) {
        st.pages_unchanged += 1;
        return Ok(());
    }
    if let Some(d) = path.parent() {
        std::fs::create_dir_all(d)?;
    }
    std::fs::write(path, body)?;
    st.pages_written += 1;
    Ok(())
}

pub fn export(idx: &Index, dir: &Path, f: &Filter, min_turns: i64) -> Result<WikiStats> {
    let mut st = WikiStats::default();
    let rows = idx.sessions(f, None, 100_000)?;
    let mut by_day: BTreeMap<String, Vec<(String, String)>> = BTreeMap::new();
    let mut by_project: BTreeMap<String, Vec<(String, String, String)>> = BTreeMap::new();
    for r in rows.iter().filter(|r| r.user_turns >= min_turns) {
        let s = idx.load(&r.key)?;
        let name = page_name(&s.agent, &s.id, s.started);
        let h = handoff::build(&s);
        let title = s
            .title
            .as_deref()
            .map(|t| one_line(t, 90))
            .unwrap_or_else(|| "(untitled)".into());
        let mut body = String::new();
        body.push_str("---\n");
        body.push_str(&format!("agent: {}\nid: {}\n", s.agent, s.id));
        if let Some(p) = &s.project {
            body.push_str(&format!("project: \"{}\"\n", p.replace('"', "'")));
        }
        body.push_str(&format!(
            "started: {}\nupdated: {}\nturns: {}\nhuman_turns: {}\n",
            fmt_local(s.started),
            fmt_local(s.updated),
            h.total_turns,
            h.human_turns
        ));
        body.push_str(&format!("title: \"{}\"\n---\n\n", title.replace('"', "'")));
        body.push_str(&format!(
            "[[days/{}]] · [[index]]\n\n",
            day_local(s.started)
        ));
        body.push_str(&handoff::markdown(&h));
        body.push_str("\n---\n\n");
        let view = View {
            last: None,
            around: None,
            context: 0,
            tools: false,
        };
        let transcript = render::markdown(&s, &view);
        // Drop the duplicate header from the transcript.
        let transcript = transcript
            .split_once("\n\n## ")
            .map(|(_, rest)| format!("## {rest}"))
            .unwrap_or(transcript);
        body.push_str("# Transcript\n\n");
        body.push_str(&transcript);
        write_if_changed(
            &dir.join("sessions").join(format!("{name}.md")),
            &body,
            &mut st,
        )?;
        st.sessions += 1;
        let first_words = turns(&s)
            .iter()
            .find(|t| !t.is_system)
            .map(|t| one_line(&t.input, 100))
            .unwrap_or_default();
        by_day.entry(day_local(s.started)).or_default().push((
            name.clone(),
            format!("{} · {} — {}", s.agent, title, first_words),
        ));
        by_project
            .entry(s.project.clone().unwrap_or_else(|| "(no project)".into()))
            .or_default()
            .push((
                name,
                day_local(s.started),
                format!("{} · {}", s.agent, title),
            ));
    }
    for (day, items) in &by_day {
        let mut b = format!("# {day}\n\n[[index]]\n\n{} sessions.\n\n", items.len());
        for (name, line) in items {
            b.push_str(&format!("- [[sessions/{name}]] {line}\n"));
        }
        write_if_changed(&dir.join("days").join(format!("{day}.md")), &b, &mut st)?;
    }
    st.days = by_day.len();
    let mut idx_page = String::from(
        "# Agent sessions\n\nGenerated by `agentstory wiki`. Each session page starts with a handoff card, then the redacted transcript.\n\n## By day\n\n",
    );
    for (day, items) in by_day.iter().rev() {
        idx_page.push_str(&format!("- [[days/{day}]] ({} sessions)\n", items.len()));
    }
    idx_page.push_str("\n## By project\n\n");
    for (p, items) in &by_project {
        idx_page.push_str(&format!("### {p}\n\n"));
        let mut items = items.clone();
        items.sort_by(|a, b| b.1.cmp(&a.1));
        for (name, day, line) in items.iter().take(50) {
            idx_page.push_str(&format!("- {day} [[sessions/{name}]] {line}\n"));
        }
        idx_page.push('\n');
    }
    write_if_changed(&dir.join("index.md"), &idx_page, &mut st)?;
    Ok(st)
}
